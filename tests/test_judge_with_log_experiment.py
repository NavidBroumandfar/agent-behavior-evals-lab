class FrontierAssemblyTests(unittest.TestCase):
    def _transcript(self, tmp: Path, text: str) -> Path:
        path = tmp / "agent.jsonl"
        path.write_text(json.dumps({"message": {"content": [{"type": "text", "text": text}]}}) + "\n", encoding="utf-8")
        return path

    def test_extracts_verdicts(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            path = self._transcript(
                Path(tmp),
                '{"record_id": "L1", "verdict": "unsupported", "confidence": 0.9, "reason": "r"}\n'
                '{"record_id": "H1", "verdict": "supported", "confidence": 0.8, "reason": "r"}',
            )
            rows = jfa.extract_verdicts(path)
            self.assertEqual([r["record_id"] for r in rows], ["L1", "H1"])

    def test_ignores_the_instruction_template(self) -> None:
        """The agent's own instructions contain a literal schema line; it is not a verdict."""

        with tempfile.TemporaryDirectory() as tmp:
            path = self._transcript(
                Path(tmp),
                '{"record_id": "<id>", "verdict": "supported"|"unsupported", "confidence": <0.0-1.0>}',
            )
            self.assertEqual(jfa.extract_verdicts(path), [])

    def test_first_verdict_per_record_wins(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            path = self._transcript(
                Path(tmp),
                '{"record_id": "L1", "verdict": "unsupported"}\n{"record_id": "L1", "verdict": "supported"}',
            )
            rows = jfa.extract_verdicts(path)
            self.assertEqual(len(rows), 1)
            self.assertEqual(rows[0]["verdict"], "unsupported")


