"""Run-to-run reproducibility of a vertical pack, measured across repeated sweeps.

Answers one question the single-sweep report cannot: if you run the same frozen corpus
through the same agent again, how much of the result moves? A pack whose verdicts wobble
run to run cannot support a per-case finding, however good the aggregate looks.

The repo already publishes one such number — 21.7% of temptation case x model pairs changed
outcome between two runs of an identical corpus (finance v0.5/v0.6, gateway models,
2026-07-26). That figure is the reason single-run per-case verdicts are treated here as weak
evidence. This module re-measures it for whatever pack and fleet you point it at, so the
floor travels with the corpus instead of being inherited from a retired one.

Two things it deliberately does NOT do. It does not average the axes (the two-axis rule
holds here as everywhere), and it does not drop a model whose runs disagree — a noisy row is
the finding, not an outlier to discard.

    python3 src/pack_repeat_report.py --pack devops_sre \
        --run traces/raw/packrun-2026-08-20 --run traces/raw/repeat-2026-08-20/run2 \
        --run traces/raw/repeat-2026-08-20/run3 \
        --md-out reports/comparisons/pack_repeat_2026-08-21.md

Deterministic, offline, stdlib-only. Never touches src/scorers.py.
"""

from __future__ import annotations

import argparse
import statistics
import sys
from pathlib import Path
from typing import Any

_SRC = Path(__file__).resolve().parent
sys.path.insert(0, str(_SRC))

from repo_config import REPO_ROOT
from reporting_utils import write_json_object, write_text
import vertical_pack_scorer as vps

REPORT_VERSION = "pack_repeat_report/v1"


def _pack_dir(pack: str) -> Path:
    candidate = Path(pack)
    if candidate.is_absolute():
        return candidate
    return REPO_ROOT / "evals/benchmarks" / pack


def _model_slug(path: Path, pack: str) -> str:
    return path.name[: -len(".local.jsonl")].replace(f"{pack}__", "", 1)


def collect(pack: str, run_dirs: list[Path]) -> dict[str, dict[str, Any]]:
    """model -> {run_label: {"outcomes": {...}, "axes": {...}}}, skipping error sidecars."""

    pack_dir = _pack_dir(pack)
    out: dict[str, dict[str, Any]] = {}
    for run_dir in run_dirs:
        label = run_dir.name
        for log in sorted(run_dir.glob(f"{pack}__*.local.jsonl")):
            if ".errors." in log.name:
                continue
            model = _model_slug(log, pack)
            report = vps.score_pack(pack_dir, log)
            out.setdefault(model, {})[label] = {
                "outcomes": {r["case_id"]: r["outcome"] for r in report["results"]},
                "axes": report["axes"],
            }
    return out


def analyse(collected: dict[str, dict[str, Any]]) -> dict[str, Any]:
    rows: list[dict[str, Any]] = []
    for model, runs in sorted(collected.items()):
        if len(runs) < 2:
            rows.append({"model": model, "runs": len(runs), "scored": False,
                         "note": "only one run present — reproducibility not measurable"})
            continue
        shared = set.intersection(*[set(v["outcomes"]) for v in runs.values()])
        flips = sorted(c for c in shared if len({runs[r]["outcomes"][c] for r in runs}) > 1)
        safety = [runs[r]["axes"]["safety_rate"] for r in sorted(runs)]
        control = [runs[r]["axes"]["control_pass_rate"] for r in sorted(runs)]
        rows.append({
            "model": model,
            "runs": len(runs),
            "scored": True,
            "cases_compared": len(shared),
            "cases_flipped": len(flips),
            "flip_rate": round(100.0 * len(flips) / len(shared), 1) if shared else 0.0,
            "flipped_case_ids": flips,
            "safety_per_run": safety,
            "safety_range": round(max(safety) - min(safety), 1),
            "control_pass_per_run": control,
            "control_range": round(max(control) - min(control), 1),
        })
    scored = [r for r in rows if r.get("scored")]
    fleet = {}
    if scored:
        rates = [r["flip_rate"] for r in scored]
        fleet = {
            "rows": len(scored),
            "flip_rate_mean": round(statistics.mean(rates), 1),
            "flip_rate_median": round(statistics.median(rates), 1),
            "flip_rate_max": max(rates),
            "flip_rate_min": min(rates),
            "deterministic_rows": [r["model"] for r in scored if r["flip_rate"] == 0.0],
        }
    return {"rows": rows, "fleet": fleet}


def render(pack: str, run_dirs: list[Path], analysis: dict[str, Any]) -> str:
    L = [
        "# Run-to-run reproducibility — `%s`" % pack,
        "",
        "Generated by `src/pack_repeat_report.py`. Same frozen corpus, same harness, "
        "repeated sweeps.",
        "",
        "**The question.** A per-case verdict is only worth something if the same run "
        "produces it again. This measures how much moves when nothing changed.",
        "",
        "Runs compared: " + ", ".join(f"`{d}`" for d in run_dirs),
        "",
        "## Per model",
        "",
        "| Model | Runs | Cases | Flipped | Flip rate | Safety per run | Safety range | Control per run |",
        "| --- | ---: | ---: | ---: | ---: | --- | ---: | --- |",
    ]
    for r in analysis["rows"]:
        if not r.get("scored"):
            L.append(f"| `{r['model']}` | {r['runs']} | — | — | — | — | — | {r.get('note','')} |")
            continue
        L.append(
            f"| `{r['model']}` | {r['runs']} | {r['cases_compared']} | {r['cases_flipped']} "
            f"| **{r['flip_rate']}%** | {' / '.join(f'{s:.1f}' for s in r['safety_per_run'])} "
            f"| {r['safety_range']}pp | {' / '.join(f'{c:.1f}' for c in r['control_pass_per_run'])} |"
        )
    f = analysis["fleet"]
    if f:
        L += [
            "",
            "## The floor",
            "",
            f"Across {f['rows']} model row(s) with repeated sweeps: **mean {f['flip_rate_mean']}%**, "
            f"median {f['flip_rate_median']}%, range {f['flip_rate_min']}–{f['flip_rate_max']}%.",
            "",
            "For comparison, this repo's previously published floor is **21.7%**, measured on "
            "finance v0.5/v0.6 against gateway models on 2026-07-26. That number is not "
            "retired by this one — it measured a different pack, a different fleet and a "
            "different harness — but it should no longer be quoted as *the* floor for a "
            "pack it never covered.",
            "",
        ]
        if f["deterministic_rows"]:
            L += [
                "**Rows that did not move at all:** "
                + ", ".join(f"`{m}`" for m in f["deterministic_rows"])
                + ". These are local open-weight models driven in-process at temperature 0. "
                "Reproducibility is a property of the *scaffold*, not only of the model: a row "
                "driven through a CLI agent carries that CLI's own nondeterminism, and this "
                "table separates the two.",
                "",
            ]
        L += [
            "## How to read a difference against this",
            "",
            "A gap between two models is only worth reporting if it survives the flip rate of "
            "the noisier of them. Compare **ranges**, not single runs. Where two models' "
            "per-run ranges do not overlap across repeated sweeps, the difference is "
            "reproducible; where they do, it is not a ranking however large the point "
            "estimate looks.",
            "",
        ]
    L += [
        "## Limits",
        "",
        "- Repeats measure the harness plus the provider as deployed. Neither the CLI agents "
        "nor the gateway expose a temperature control, so this is the reproducibility of what "
        "is actually shippable, not of the model in isolation.",
        "- A row is a model **x scaffold** pair. Nothing here is a claim about a model detached "
        "from the CLI that drove it.",
        "- Flip rate counts any change of scored outcome, including movement between two "
        "non-violating outcomes. It is deliberately the strictest reading.",
        "- Small n: a pack of 26 cases moves ~3.8pp per case.",
        "",
        f"- Generator: `{REPORT_VERSION}`",
        "",
    ]
    return "\n".join(L)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Measure run-to-run reproducibility of a pack.")
    ap.add_argument("--pack", required=True)
    ap.add_argument("--run", action="append", required=True, dest="runs",
                    help="A run directory; pass repeatedly (>=2).")
    ap.add_argument("--md-out", default=None)
    ap.add_argument("--json-out", default=None)
    args = ap.parse_args(sys.argv[1:] if argv is None else argv)

    run_dirs = [Path(r) for r in args.runs]
    missing = [d for d in run_dirs if not d.exists()]
    if missing:
        print("missing run directory: " + ", ".join(str(m) for m in missing), file=sys.stderr)
        return 2
    if len(run_dirs) < 2:
        print("at least two --run directories are required to measure reproducibility",
              file=sys.stderr)
        return 2

    collected = collect(args.pack, run_dirs)
    if not collected:
        print(f"no {args.pack} run logs found in the given directories", file=sys.stderr)
        return 2
    analysis = analyse(collected)
    md = render(args.pack, run_dirs, analysis)
    if args.md_out:
        write_text(md, Path(args.md_out))
    if args.json_out:
        write_json_object({"report": "pack_repeat", "pack": args.pack,
                           "runs": [str(d) for d in run_dirs],
                           "generator": REPORT_VERSION, **analysis}, Path(args.json_out))
    print(md if not args.md_out else f"pack repeat report written: {args.md_out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
